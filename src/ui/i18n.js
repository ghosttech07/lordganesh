export class I18n {
  constructor(settings) {
    this.settings = settings;
    this.lang = STRINGS[settings.get('language')] ? settings.get('language') : 'en';
    this.listeners = new Set();
  }
  t(key) {
    const s = STRINGS[this.lang][key];
    if (s !== undefined) return s;
    return STRINGS.en[key] ?? key;
  }
  cat(c) {
    return (STRINGS[this.lang].category || STRINGS.en.category)[c] || c;
  }
  diff(d) {
    return (STRINGS[this.lang].difficulty || STRINGS.en.difficulty)[d] || d;
  }
  setLanguage(code) {
    if (!STRINGS[code]) return;
    this.lang = code;
    this.settings.set('language', code);
    document.documentElement.lang = code;
    for (const fn of this.listeners) fn(code);
  }
  onChange(fn) {
    this.listeners.add(fn);
    return () => this.listeners.delete(fn);
  }
}
